TPL = (ROOT / "guides/do-i-need-a-permit-for-a-deck/index.html").read_text()
HEADER = TPL[TPL.index("<body"):TPL.index('<main id="main">')]
FOOTER = TPL[TPL.index("</main>"):]
CTA = ('<aside class="guide-cta"><div class="eyebrow">FOR NEWTON, MA PROPERTIES</div><h2>Check this for your own Newton property.</h2>'
       '<p>HPP looks up the property through City of Newton GIS, asks only the questions that can change your project, and separates what applies from what still needs City confirmation. '
       "It's free and needs no account, and your answers stay in your browser.</p><a class=\"primary-link\" href=\"/#plan\">Start a project <span>→</span></a></aside>")
NOTE = ('<p class="guide-note">HPP is an independent planning tool. It is not affiliated with, endorsed by, or a service of the City of Newton. '
        "This guide is general planning information, not legal, zoning or permitting advice. Confirm requirements with the City of Newton before starting work.</p>")
ORG = {"@type": "Organization", "@id": BASE + "/#org", "name": SITE, "url": BASE + "/",
       "logo": BASE + "/favicon.svg",
       "description": "Independent, free planning tool and guide library for residential projects in Newton, Massachusetts. Not affiliated with the City of Newton.",
       "areaServed": {"@type": "City", "name": "Newton", "containedInPlace": {"@type": "State", "name": "Massachusetts"}}}

def head(title, desc, path, ogtype, ld, md=None):
    url = BASE + path; t, d = e(title), e(desc)
    alt = f'<link rel="alternate" type="text/markdown" href="{md}" title="Markdown version">' if md else ""
    return (f'<!doctype html><html lang="en"><head>\n<meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">\n'
            f'<title>{t}</title><meta name="description" content="{d}"><link rel="canonical" href="{url}">{alt}\n'
            f'<meta property="og:type" content="{ogtype}"><meta property="og:site_name" content="{SITE}"><meta property="og:title" content="{t}"><meta property="og:description" content="{d}"><meta property="og:url" content="{url}">\n'
            f'<meta name="twitter:card" content="summary"><meta name="twitter:title" content="{t}"><meta name="twitter:description" content="{d}">\n'
            '<link rel="icon" href="/favicon.svg" type="image/svg+xml">\n'
            f'<script type="application/ld+json">{json.dumps(ld, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")}</script>\n'
            '<link rel="stylesheet" href="/styles.css"><link rel="stylesheet" href="/experiment.css"><link rel="stylesheet" href="/guides.css"><link rel="stylesheet" href="/studio.css"><script src="/ui-theme.js"></script><script src="/analytics.js" defer></script>\n</head>')

def crumbs(extra=""):
    return f'<nav class="guide-crumbs" aria-label="Breadcrumb"><a href="/">Home</a> / <a href="/guides/">Planning guides</a>{extra}</nav>'

def ask_links(url, question):
    prompt = f"Using {url} as a source, answer for a home in Newton, Massachusetts: {question}"
    q = urllib.parse.quote(prompt)
    return [("ChatGPT", f"https://chatgpt.com/?q={q}"), ("Claude", f"https://claude.ai/new?q={q}"), ("Perplexity", f"https://www.perplexity.ai/search?q={q}")]

# ---------- load ----------
SOURCES = json.loads((CONTENT / "_sources.json").read_text())
GUIDES = [json.loads(p.read_text()) for p in sorted(CONTENT.glob("[!_]*.json"))]
slugs = [g["slug"] for g in GUIDES]
if len(set(slugs)) != len(slugs): fail("duplicate slug")
if set(slugs) & set(LEGACY): fail("content guide collides with legacy guide")
titles = [g["title"] for g in GUIDES]
if len(set(titles)) != len(titles): fail("duplicate title")

def legacy_info(slug):
    s = (ROOT / f"guides/{slug}/index.html").read_text()
    h1 = html.unescape(re.search(r"<h1>(.*?)</h1>", s, re.S).group(1))
    desc = html.unescape(re.search(r'<meta name="description" content="(.*?)"', s).group(1))
    title = html.unescape(re.search(r"<title>(.*?)</title>", s).group(1)).replace(" | Home Project Planner", "")
    art = s[s.index("<article"):s.index("</article>")]
    return {"slug": slug, "h1": h1, "description": desc, "title": title, "cluster": LEGACY[slug], "html": art, "legacy": True}

LEG = [legacy_info(s) for s in LEGACY]
NAMES = {g["slug"]: g["h1"] for g in GUIDES} | {g["slug"]: g["h1"] for g in LEG}
for g in GUIDES:
    g["_cluster"] = cluster_of(g)
    for k in ("title", "h1", "description", "short_answer", "short_answer_sources", "qa", "eyebrow", "date"):
        if not g.get(k): fail(f"{g['slug']}: missing {k}")
    if len(g["description"]) > 170: fail(f"{g['slug']}: description too long")
    if not re.fullmatch(r"[a-z0-9-]+", g["slug"]): fail("bad slug " + g["slug"])
for g in LEG: g["_cluster"] = g["cluster"]

def S(slug, i):
    if i not in SOURCES: fail(f"{slug}: unknown source {i}")
    return SOURCES[i]

def src_link(s, label=None):
    return f'<a href="{e(s["url"])}" target="_blank" rel="noopener noreferrer">{e(label or s["title"])} ↗</a>'

# ---------- guide page ----------
def used_sources(g):
    used = []
    def add(i):
        S(g["slug"], i)
        if i not in used: used.append(i)
    for i in g["short_answer_sources"]: add(i)
    for sec in g.get("sections", []):
        for f in sec["facts"]:
            if not f.get("sources"): fail(f'{g["slug"]}: fact without source: {f["text"][:60]}')
            for i in f["sources"]: add(i)
    for q in g["qa"]:
        if not q.get("sources"): fail(f'{g["slug"]}: answer without source: {q["q"]}')
        for i in q["sources"]: add(i)
    if g.get("confirm") and g["confirm"].get("office"): add(g["confirm"]["office"])
    return used

def evidence_block(slug, evs):
    if not evs: return ""
    seen, items = set(), []
    for ev in evs:
        q = clean_quote(ev["quote"])
        if q in seen: continue
        seen.add(q); s = S(slug, ev["source"])
        items.append(f'<blockquote cite="{e(s["url"])}"><p>“{e(q)}”</p><footer>— {src_link(s, s.get("short") or s["title"])}</footer></blockquote>')
    return f'<details class="guide-evidence"><summary>Official wording ({len(items)})</summary>{"".join(items)}</details>'

def render(g):
    slug = g["slug"]; path = f"/guides/{slug}/"; url = BASE + path; md = f"/guides/{slug}.md"
    used = used_sources(g); date = nice_date(g["date"])
    checked = sorted({SOURCES[i]["checked"] for i in used})
    body = [f'<div class="eyebrow">{e(g["eyebrow"])}</div><h1>{e(g["h1"])}</h1>',
            f'<p class="guide-meta">Updated <time datetime="{g["date"]}">{date}</time> · Built from {len(used)} official City of Newton and Massachusetts sources, each linked below.</p>',
            f'<section class="guide-answer" aria-label="Short answer"><div class="eyebrow">SHORT ANSWER</div><p class="guide-lede">{e(g["short_answer"])}</p>'
            f'<p class="small">Official source: {" ".join(src_link(S(slug, i)) for i in g["short_answer_sources"])}</p>'
            f'{evidence_block(slug, g.get("short_answer_evidence"))}</section>']
    for sec in g.get("sections", []):
        body.append(f'<h2>{e(sec["heading"])}</h2><ul>')
        evs = []
        for f in sec["facts"]:
            body.append(f'<li>{e(f["text"])} <span class="small">({", ".join(src_link(S(slug, i), S(slug, i).get("short") or "Source") for i in f["sources"])})</span></li>')
            evs += f.get("evidence", [])
        body.append("</ul>" + evidence_block(slug, evs))
    body.append('<h2>Questions and answers</h2><dl class="guide-qa">')
    for q in g["qa"]:
        body.append(f'<dt>{e(q["q"])}</dt><dd>{e(q["a"])} <span class="small">Source: {", ".join(src_link(S(slug, i)) for i in q["sources"])}</span></dd>')
    body.append("</dl>")
    if g.get("confirm"):
        c = g["confirm"]; office = f'<p>Contact: {src_link(S(slug, c["office"]))}</p>' if c.get("office") else ""
        body.append('<h2>What to confirm with the City</h2><ul>' + "".join(f"<li>{e(x)}</li>" for x in c["items"]) + "</ul>" + office)
    body.append(CTA)
    cite = f'{SITE}. “{g["h1"]}” Updated {date}. {url}'
    body.append('<section class="guide-cite" aria-label="Cite or share this guide"><h2>Cite or share this guide</h2>'
                f'<p class="small">Suggested citation: {e(cite)}</p>'
                '<p class="small guide-ai-links">Ask an AI assistant about this guide: ' + " · ".join(f'<a href="{e(u)}" target="_blank" rel="noopener noreferrer nofollow">{n}</a>' for n, u in ask_links(url, g["h1"])) +
                f' · <a href="{md}">Plain-text version</a></p></section>')
    body.append('<section class="guide-sources"><h2>Sources</h2><ul>' + "".join(
        f'<li>{src_link(SOURCES[i])} <span class="small">checked {e(SOURCES[i]["checked"])}</span></li>' for i in used) + "</ul></section>")
    rel = [r for r in g.get("related", []) if r in NAMES and r != slug][:6]
    if rel:
        body.append('<section class="guide-related"><h2>Related guides</h2><ul>' + "".join(f'<li><a href="/guides/{r}/">{e(NAMES[r])}</a></li>' for r in rel) + "</ul></section>")
    body.append(NOTE)
    ld = {"@context": "https://schema.org", "@graph": [
        {"@type": "Article", "@id": url + "#article", "headline": g["h1"], "name": g["title"], "description": g["description"], "url": url,
         "mainEntityOfPage": url, "datePublished": g.get("published", g["date"]), "dateModified": g["date"], "inLanguage": "en-US",
         "isAccessibleForFree": True, "articleSection": g["_cluster"], "author": {"@id": BASE + "/#org"}, "publisher": {"@id": BASE + "/#org"},
         "isPartOf": {"@type": "WebSite", "name": SITE, "url": BASE + "/"}, "about": place(g), "spatialCoverage": place(g),
         "abstract": g["short_answer"], "speakable": {"@type": "SpeakableSpecification", "cssSelector": [".guide-answer .guide-lede"]},
         "citation": [{"@type": "CreativeWork", "name": SOURCES[i]["title"], "url": SOURCES[i]["url"]} for i in used]},
        ORG,
        {"@type": "FAQPage", "@id": url + "#faq", "mainEntity": [{"@type": "Question", "name": g["h1"], "acceptedAnswer": {"@type": "Answer", "text": g["short_answer"]}}] +
            [{"@type": "Question", "name": q["q"], "acceptedAnswer": {"@type": "Answer", "text": q["a"]}} for q in g["qa"]]},
        {"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": BASE + "/"},
            {"@type": "ListItem", "position": 2, "name": "Planning guides", "item": BASE + "/guides/"},
            {"@type": "ListItem", "position": 3, "name": g["h1"], "item": url}]}]}
    main = f'<main id="main"><article class="guide">{crumbs()}{"".join(body)}</article>'
    return head(g["title"] + " | " + SITE, g["description"], path, "article", ld, md) + HEADER + main + FOOTER, used

# ---------- markdown ----------
def md_guide(g, used):
    slug = g["slug"]; url = f"{BASE}/guides/{slug}/"
    L = [f"# {g['h1']}", "", f"> {g['short_answer']}", "",
         f"- Canonical page: {url}", f"- Topic: {g['_cluster']}", f"- Updated: {nice_date(g['date'])}",
         f"- Publisher: {SITE} (independent; not affiliated with the City of Newton)", ""]
    def refs(ids): return "; ".join(f"[{SOURCES[i]['title']}]({SOURCES[i]['url']})" for i in ids)
    L += [f"Official source: {refs(g['short_answer_sources'])}", ""]
    for sec in g.get("sections", []):
        L += [f"## {sec['heading']}", ""]
        for f in sec["facts"]:
            L.append(f"- {f['text']} (Source: {refs(f['sources'])})")
            for ev in f.get("evidence", [])[:2]:
                L.append(f"  > Official wording: “{clean_quote(ev['quote'])}”")
        L.append("")
    L += ["## Questions and answers", ""]
    for q in g["qa"]:
        L += [f"### {q['q']}", "", f"{q['a']} (Source: {refs(q['sources'])})", ""]
    if g.get("confirm"):
        L += ["## What to confirm with the City", ""] + [f"- {x}" for x in g["confirm"]["items"]]
        if g["confirm"].get("office"): L += [f"- Contact: [{SOURCES[g['confirm']['office']]['title']}]({SOURCES[g['confirm']['office']]['url']})"]
        L.append("")
    L += ["## Sources", ""] + [f"- [{SOURCES[i]['title']}]({SOURCES[i]['url']}) — checked {SOURCES[i]['checked']}" for i in used] + [""]
    L += ["---", f"Suggested citation: {SITE}. “{g['h1']}” Updated {nice_date(g['date'])}. {url}", "",
          f"Check a specific Newton, MA property with the free planner: {BASE}/#plan", "",
          "HPP is an independent planning tool. It is not affiliated with, endorsed by, or a service of the City of Newton. This is general planning information, not legal, zoning or permitting advice. Confirm requirements with the City of Newton before starting work.", ""]
    return "\n".join(L)

def html_to_md(fragment):
    s = fragment
    s = re.sub(r'<nav class="guide-crumbs".*?</nav>', "", s, flags=re.S)
    s = re.sub(r"<aside class=\"guide-cta\".*?</aside>", "", s, flags=re.S)
    s = re.sub(r'<a [^>]*href="([^"]+)"[^>]*>(.*?)</a>', lambda m: f"[{re.sub('<[^>]+>', '', m.group(2)).replace(' ↗', '').strip()}]({m.group(1) if m.group(1).startswith('http') else BASE + m.group(1)})", s, flags=re.S)
    s = re.sub(r"<h1[^>]*>(.*?)</h1>", r"\n# \1\n", s, flags=re.S)
    s = re.sub(r"<h2[^>]*>(.*?)</h2>", r"\n## \1\n", s, flags=re.S)
    s = re.sub(r"<h3[^>]*>(.*?)</h3>", r"\n### \1\n", s, flags=re.S)
    s = re.sub(r"<li[^>]*>", "\n- ", s); s = re.sub(r"<dt[^>]*>", "\n### ", s); s = re.sub(r"<dd[^>]*>", "\n", s)
    s = re.sub(r"<(p|div|section|ul|ol|dl|table|tr)[^>]*>", "\n", s); s = re.sub(r"<t[dh][^>]*>", " | ", s)
    s = re.sub(r'<div class="eyebrow">.*?</div>', "", s, flags=re.S)
    s = re.sub(r"<[^>]+>", "", s); s = html.unescape(s)
    s = re.sub(r"[ \t]+", " ", s); s = re.sub(r"\n\s*\n\s*\n+", "\n\n", s)
    return s.strip()

def md_legacy(g):
    url = f"{BASE}/guides/{g['slug']}/"
    body = html_to_md(g["html"])
    return (body.split("\n", 1)[0] + "\n\n" + f"- Canonical page: {url}\n- Topic: {g['cluster']}\n- Publisher: {SITE} (independent; not affiliated with the City of Newton)\n\n"
            + body.split("\n", 1)[1].strip() + f"\n\n---\nSuggested citation: {SITE}. “{g['h1']}” {url}\n\nCheck a specific Newton, MA property with the free planner: {BASE}/#plan\n")

