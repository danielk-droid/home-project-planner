#!/usr/bin/env python3
"""Build the HPP planning-guide library and its AI/search discovery files.

Inputs : content/_sources.json and content/<slug>.json (one per guide). Every fact, short answer
         and Q&A answer carries source ids and, for guides from 2026-11 onward, verbatim official
         wording ("evidence") that was machine-checked against the live source text.
Outputs (under --root, default = repository root two levels up):
  guides/<slug>/index.html   guide pages            guides/<slug>.md       Markdown twin
  guides/index.html          library by topic       guides/quick-answers/  every short answer
  guides/guides.json         machine-readable set   llms.txt, llms-full.txt
  sitemap.xml, robots.txt
Legacy guides (scripts/generate-guides.py) keep their HTML; this script only indexes them.
The build fails on any fact without a source, unknown source ids, duplicate slugs/titles,
or over-long descriptions."""
import json, html, re, sys, pathlib, datetime, urllib.parse
HERE = pathlib.Path(__file__).resolve().parent
ROOT = pathlib.Path(sys.argv[sys.argv.index("--root") + 1]).resolve() if "--root" in sys.argv else HERE.parents[1]
CONTENT = HERE / "content"
BASE = "https://home-project-planner-mvp.vercel.app"
SITE = "Home Project Planner"
e = html.escape

LEGACY = {  # hand-written guides generated by scripts/generate-guides.py
    "do-i-need-a-permit-for-an-addition": "Permits by project",
    "do-i-need-a-permit-for-a-deck": "Permits by project",
    "building-permit-vs-zoning-approval": "Permit process",
    "how-much-can-i-build-on-my-lot": "Zoning rules",
    "historic-home-renovation": "Historic",
    "stormwater-and-flood-zone-home-projects": "Site & environment",
    "questions-before-starting-a-home-project": "Permit process",
}
CLUSTERS = [
    ("Permit process", "How Newton building permits, inspections, fees and closeout work."),
    ("Permits by project", "Which permits common home projects need in Newton, MA."),
    ("Building code", "Massachusetts State Building Code (780 CMR) requirements homeowners ask about."),
    ("Zoning rules", "Newton zoning limits: setbacks, height, FAR, lot coverage, parking and more."),
    ("Zoning relief & appeals", "Special permits, variances, the ZBA, abutter notice and appeals."),
    ("ADUs", "Accessory dwelling units under Massachusetts law and Newton's ordinance."),
    ("Historic", "Local historic districts, landmarks, demolition delay and historic review."),
    ("Site & environment", "Wetlands, flood zones, trees, digging, driveways, sewer and street work."),
    ("Energy & mechanical", "Energy code, heat pumps, EV chargers, batteries, wood stoves and rebates."),
    ("Contractors & trades", "Licenses, registrations, contracts and who may do trade work in Massachusetts."),
    ("Records & property info", "Property records, plans, public records and certificates."),
]
CLUSTER_ALIASES = {"Zoning": "Zoning rules", "Energy": "Energy & mechanical", "Site": "Site & environment",
                   "Trades": "Contractors & trades", "Environment": "Site & environment", "Trees &amp; Historic": "Historic", "Trees & Historic": "Historic", "Zoning relief &amp; appeals": "Zoning relief & appeals", "Contractors & consumer law": "Contractors & trades"}
RELIEF = re.compile(r"(zoning-board|special-permit|variance|appeal|abutter|enforcement-time|nonconforming-single-family|zoning-relief)")
CODE = re.compile(r"(egress|stair|ceiling-height|smoke-and-carbon|heat-detector|fire-separation|safety-glass|habitable-room|exhaust-fan|alarm|deck-construction-code|780-cmr|building-code|exempt-from-a-building-permit|emergency-repair)")

def fail(msg): print("GUIDE BUILD ERROR:", msg); sys.exit(1)
def nice_date(iso): d = datetime.date.fromisoformat(iso); return d.strftime("%B ") + str(d.day) + d.strftime(", %Y")
def clean_quote(q):
    q = re.sub(r"</?u>|</?sup>|</?em>|</?strong>", "", q)
    q = re.sub(r"[*_`]+", "", q); q = re.sub(r"\s+", " ", q).strip()
    return q

def cluster_of(g):
    c = CLUSTER_ALIASES.get(g["cluster"], g["cluster"])
    if c in ("Zoning rules",) and RELIEF.search(g["slug"]): c = "Zoning relief & appeals"
    if c in ("Permits by project", "Permit process") and CODE.search(g["slug"]): c = "Building code"
    if c not in dict(CLUSTERS): fail(f'{g["slug"]}: unknown cluster {c}')
    return c

def place(g):
    t = (g["slug"] + " " + g["h1"]).lower()
    newton = {"@type": "City", "name": "Newton", "containedInPlace": {"@type": "State", "name": "Massachusetts"}}
    return newton if "newton" in t else {"@type": "State", "name": "Massachusetts"}

