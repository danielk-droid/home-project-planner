// Generates docs/professional-review-packet.md (REV-002) from the live registries.
// Every field is read from repository data; nothing is authored by hand, so the
// packet cannot claim a version, date, or review that the data does not contain.
// Usage: node scripts/build-review-packet.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { requiredFacts, factProvenance } from '../src/governance.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const rules = read('data/rules.json');
const registry = read('data/governance/rule_registry.json').rules;
const sources = Object.fromEntries(read('data/governance/source_registry.json').sources.map(s => [s.sourceId, s]));
const sourceMeta = read('data/sources.json');
const sourceList = Array.isArray(sourceMeta) ? sourceMeta : (sourceMeta.sources || Object.values(sourceMeta));
const sourceUrl = Object.fromEntries(sourceList.filter(s => s && s.id).map(s => [s.id, s]));
const testDir = path.join(root, 'tests');
const tests = fs.readdirSync(testDir).filter(f => f.endsWith('.mjs')).map(f => [f, fs.readFileSync(path.join(testDir, f), 'utf8')]);

const critical = registry.filter(r => r.riskClass === 'critical');
const lines = [
  '# Professional review packet (REV-002)',
  '',
  '> Generated by `node scripts/build-review-packet.mjs` from `data/rules.json` and `data/governance/*`. Do not edit by hand.',
  '> Status: **NOT professionally reviewed.** Automated tests are not professional validation. No rule below has been reviewed by a qualified professional.',
  '',
  'HPP is an independent preliminary planning tool, not affiliated with the City of Newton. Each rule below is evaluated deterministically: when its `Trigger` condition is true for the project facts, HPP shows the stated status and action. When a required fact is unknown, the listed uncertainty companion rules produce a "needs confirmation" result instead of a confident answer.',
  '',
  '## How to review',
  '',
  'For each rule, please answer the reviewer question and note: (1) correct / incorrect / incomplete, (2) the controlling citation you relied on, (3) any case where HPP would be more confident than it should be. Return notes to the owner; the owner records the outcome in the private review repository.',
  '',
  'Dimensional zoning values (SR1–SR3 setbacks, coverage, height, FAR, pre/post 12/7/1953 lots) are in `data/zoning_dimensional.json`, pinned to Newton Chapter 30 "Last Amended 12-01-25". Front-setback averaging (REV-003) and the facade/front-wall width limit (REV-004) are intentionally not evaluated.',
  '',
  `Critical rules: ${critical.length}`,
  ''
];

for (const g of critical) {
  const rule = rules.find(r => r.id === g.ruleId);
  if (!rule) throw new Error('registry rule missing from rules.json: ' + g.ruleId);
  const facts = requiredFacts(rule);
  const testFiles = tests.filter(([, body]) => body.includes(`'${g.ruleId}'`) || body.includes(`"${g.ruleId}"`)).map(([f]) => f);
  lines.push(`## ${g.ruleId} — ${rule.title}`, '');
  lines.push(`- **Purpose / action shown to user:** ${rule.action}`);
  lines.push(`- **Trigger (deterministic):** \`${rule.when}\``);
  lines.push(`- **Result status when triggered:** ${rule.status}${rule.reviewRequired ? ' (flagged for City review)' : ''}`);
  lines.push(`- **Required facts:** ${facts.length ? facts.map(f => `\`${f}\` (${factProvenance(f)})`).join(', ') : 'none'}`);
  lines.push(`- **Uncertainty behavior:** ${(g.uncertaintyCompanions || []).length ? 'if a required fact is unknown, companion rule(s) ' + g.uncertaintyCompanions.map(c => '`' + c + '`').join(', ') + ' return needs-confirmation' : 'no companion; missing facts leave the trigger false'}${g.knownGap ? `; tracked gap ${g.knownGap.code} (${g.knownGap.reviewId})` : ''}`);
  lines.push('- **Sources:**');
  for (const id of rule.sourceIds || []) {
    const s = sources[id] || {};
    const u = sourceUrl[id] || {};
    lines.push(`  - \`${id}\`${u.url ? ' ' + u.url : ''} — tier ${s.tier ?? '?'} (${s.tierLabel ?? 'unknown'}); version: ${s.versionLabel ?? 'none claimed'}; status ${s.versionStatus ?? 'unknown'}; effective date: ${s.effectiveFrom ?? 'not verified'}; last verified ${s.lastVerified ?? 'unknown'}`);
  }
  lines.push(`- **Representative / boundary tests:** ${testFiles.length ? testFiles.join(', ') : 'exercised by the release-gate rule sweep only'}`);
  lines.push(`- **Current review state:** ${g.humanReview}; interpretation ${g.interpretationStatus}`);
  lines.push(`- **Reviewer question:** Under current Newton ordinance and Massachusetts code, does "${rule.when}" correctly identify when "${rule.title}" applies, is the ${rule.status} status appropriate, and is the action wording accurate without overstating certainty?`);
  lines.push('');
}

const out = lines.join('\n');
const target = path.join(root, 'docs/professional-review-packet.md');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) {
    console.error('docs/professional-review-packet.md is stale; run node scripts/build-review-packet.mjs');
    process.exit(1);
  }
  console.log('professional review packet up to date');
} else {
  fs.writeFileSync(target, out);
  console.log('wrote docs/professional-review-packet.md (' + critical.length + ' critical rules)');
}
